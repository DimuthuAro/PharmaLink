export const exportToText = (data, options = {}) => {
    const lines = [];

    lines.push('='.repeat(60));
    lines.push('PRESCRIPTION ANALYSIS REPORT');
    lines.push('='.repeat(60));
    lines.push(`Generated: ${new Date().toLocaleString()}`);
    lines.push(`Report ID: ${generateReportId()}`);
    lines.push(`Confidence Score: ${data.confidenceScore || 0}%`);
    lines.push('');

    if (options.includePatientInfo) {
        lines.push('PATIENT INFORMATION');
        lines.push('-'.repeat(40));
        lines.push(`Name: ${data.patientName || 'Not specified'}`);
        lines.push(`Date: ${data.date || 'Not specified'}`);
        lines.push(`Doctor: ${data.doctor || 'Not specified'}`);
        lines.push('');
    }

    lines.push('MEDICATIONS');
    lines.push('-'.repeat(40));
    data.medications?.forEach((med, index) => {
        lines.push(`${index + 1}. ${med}`);
        if (data.dosages?.[index]) lines.push(`   Dosage: ${data.dosages[index]}`);
        if (data.instructions?.[index]) lines.push(`   Instructions: ${data.instructions[index]}`);
        lines.push('');
    });

    if (data.warnings?.length > 0) {
        lines.push('WARNINGS');
        lines.push('-'.repeat(40));
        data.warnings.forEach((warning, index) => {
            lines.push(`⚠️  ${warning}`);
        });
        lines.push('');
    }

    lines.push('='.repeat(60));
    lines.push('END OF REPORT');
    lines.push('='.repeat(60));
    lines.push('');
    lines.push('This report is generated by Prescription Interpreter Pro.');
    lines.push('For informational purposes only. Consult a healthcare professional.');

    return lines.join('\n');
};

export const generateQRCode = async (data, options = {}) => {
    const qrOptions = {
        width: options.width || 256,
        margin: 1,
        color: {
            dark: options.darkColor || '#000000',
            light: options.lightColor || '#FFFFFF'
        },
        errorCorrectionLevel: 'H'
    };

    try {
        const qrData = typeof data === 'string' ? data : JSON.stringify(data);
        return await QRCode.toDataURL(qrData, qrOptions);
    } catch (error) {
        console.error('QR Code generation failed:', error);
        throw error;
    }
};

export const exportToImage = async (elementId, options = {}) => {
    const element = document.getElementById(elementId);
    if (!element) {
        throw new Error(`Element with id "${elementId}" not found`);
    }

    const canvas = await html2canvas(element, {
        scale: options.scale || 2,
        useCORS: true,
        backgroundColor: options.backgroundColor || '#ffffff',
        logging: false,
        ...options
    });

    return new Promise((resolve) => {
        canvas.toBlob((blob) => {
            resolve(blob);
        }, 'image/png', 1.0);
    });
};

const escapeCSV = (str) => {
    if (str == null) return '';
    const string = String(str);
    if (string.includes(',') || string.includes('"') || string.includes('\n')) {
        return `"${string.replace(/"/g, '""')}"`;
    }
    return string;
};

const generateReportId = () => {
    return `RPT-${Date.now()}-${Math.random().toString(36).substr(2, 9).toUpperCase()}`;
};

