export const exportToPDF = async (data, options = {}) => {
    const doc = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
    });

    const {
        title = 'Prescription Analysis Report',
        includeTimestamp = true,
        includeQR = true,
        includeSignature = true
    } = options;

    // Header
    doc.setFontSize(20);
    doc.setTextColor(33, 150, 243);
    doc.text(title, 105, 20, { align: 'center' });

    doc.setFontSize(10);
    doc.setTextColor(100, 100, 100);
    doc.text(`Report ID: ${generateReportId()}`, 105, 30, { align: 'center' });

    if (includeTimestamp) {
        doc.text(`Generated: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}`, 105, 35, { align: 'center' });
    }

    // Patient Information Section
    doc.setFontSize(14);
    doc.setTextColor(0, 0, 0);
    doc.text('Patient Information', 20, 50);
    doc.setDrawColor(200, 200, 200);
    doc.line(20, 52, 190, 52);

    doc.setFontSize(10);
    const patientInfo = [
        ['Name:', data.patientName || 'Not specified'],
        ['Date of Birth:', data.dob || 'Not specified'],
        ['Prescription Date:', data.date || 'Not specified'],
        ['Doctor:', data.doctor || 'Not specified'],
        ['Clinic/Hospital:', data.clinic || 'Not specified']
    ];

    doc.autoTable({
        startY: 55,
        head: [['Field', 'Value']],
        body: patientInfo,
        theme: 'grid',
        headStyles: { fillColor: [33, 150, 243], textColor: 255 },
        styles: { fontSize: 9 },
        margin: { left: 20, right: 20 }
    });

    // Medications Table
    const medicationsY = doc.lastAutoTable.finalY + 15;
    doc.setFontSize(14);
    doc.text('Medications', 20, medicationsY);
    doc.line(20, medicationsY + 2, 190, medicationsY + 2);

    const medData = data.medications.map((med, index) => [
        index + 1,
        med,
        data.dosages?.[index] || '',
        data.instructions?.[index] || '',
        data.frequencies?.[index] || '',
        data.durations?.[index] || ''
    ]);

    doc.autoTable({
        startY: medicationsY + 5,
        head: [['#', 'Medication', 'Dosage', 'Instructions', 'Frequency', 'Duration']],
        body: medData,
        theme: 'grid',
        headStyles: { fillColor: [76, 175, 80], textColor: 255 },
        alternateRowStyles: { fillColor: [245, 245, 245] },
        styles: { fontSize: 8, cellPadding: 2 },
        margin: { left: 20, right: 20 },
        columnStyles: {
            0: { cellWidth: 10 },
            1: { cellWidth: 40 },
            2: { cellWidth: 30 },
            3: { cellWidth: 45 },
            4: { cellWidth: 25 },
            5: { cellWidth: 25 }
        }
    });

    // Warnings Section
    if (data.warnings && data.warnings.length > 0) {
        const warningsY = doc.lastAutoTable.finalY + 15;
        doc.setFontSize(14);
        doc.setTextColor(244, 67, 54);
        doc.text('Important Warnings', 20, warningsY);
        doc.setDrawColor(244, 67, 54);
        doc.line(20, warningsY + 2, 190, warningsY + 2);

        doc.setFontSize(9);
        doc.setTextColor(0, 0, 0);
        data.warnings.forEach((warning, index) => {
            const y = warningsY + 10 + (index * 6);
            doc.text(`• ${warning}`, 25, y);
        });
    }

    // Instructions Section
    if (data.instructions && data.instructions.length > 0) {
        const instructionsY = doc.lastAutoTable.finalY + (data.warnings?.length || 0) * 6 + 25;
        doc.setFontSize(14);
        doc.setTextColor(255, 152, 0);
        doc.text('Additional Instructions', 20, instructionsY);
        doc.setDrawColor(255, 152, 0);
        doc.line(20, instructionsY + 2, 190, warningsY + 2);
    }

    // Footer
    const footerY = 280;
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text('This report is generated by Prescription Interpreter Pro', 105, footerY, { align: 'center' });
    doc.text('For informational purposes only. Consult a healthcare professional.', 105, footerY + 5, { align: 'center' });

    // QR Code
    if (includeQR) {
        const qrData = JSON.stringify({
            reportId: generateReportId(),
            timestamp: new Date().toISOString(),
            medications: data.medications,
            confidence: data.confidenceScore
        });

        const qrUrl = await QRCode.toDataURL(qrData, { width: 40, margin: 1 });
        doc.addImage(qrUrl, 'PNG', 160, footerY - 15, 25, 25);
    }

    // Signature
    if (includeSignature) {
        doc.setFontSize(9);
        doc.text('Digitally Generated', 25, footerY - 10);
        doc.text(`Confidence Score: ${data.confidenceScore || 0}%`, 25, footerY - 5);
    }

    return doc.output('blob');
};

export const exportToJSON = (data, options = {}) => {
    const exportData = {
        ...data,
        metadata: {
            exportDate: new Date().toISOString(),
            version: '1.0',
            format: 'JSON',
            ...options.metadata
        }
    };

    if (options.includeRawText) {
        exportData.rawText = data.extractedText;
    }

    if (options.includeMetadata) {
        exportData.analysisMetadata = {
            confidence: data.confidenceScore,
            processingTime: data.processingTime,
            modelVersion: data.modelVersion
        };
    }

    return JSON.stringify(exportData, null, 2);
};

export const exportToCSV = (data, options = {}) => {
    const headers = ['Medication', 'Dosage', 'Instructions', 'Frequency', 'Duration', 'Warnings'];
    const rows = [];

    // Find max length
    const maxLength = Math.max(
        data.medications?.length || 0,
        data.dosages?.length || 0,
        data.instructions?.length || 0,
        data.frequencies?.length || 0,
        data.durations?.length || 0,
        data.warnings?.length || 0
    );

    for (let i = 0; i < maxLength; i++) {
        rows.push([
            data.medications?.[i] || '',
            data.dosages?.[i] || '',
            data.instructions?.[i] || '',
            data.frequencies?.[i] || '',
            data.durations?.[i] || '',
            data.warnings?.[i] || ''
        ]);
    }

    const csvContent = [
        headers.map(escapeCSV).join(','),
        ...rows.map(row => row.map(escapeCSV).join(','))
    ].join('\n');

    if (options.includeMetadata) {
        const metadata = `# Generated: ${new Date().toISOString()}\n# Confidence: ${data.confidenceScore || 0}%\n\n`;
        return metadata + csvContent;
    }

    return csvContent;
};

